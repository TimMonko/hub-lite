"""Write static/pygments.css: napari.org's code colours, light and dark.

napari.org (napari-sphinx-theme) highlights code with its own "napari"
Pygments style in light mode and Pygments' "dracula" in dark mode. This
writes the same two styles, the dark one under prefers-color-scheme, so
README code blocks on the hub look like code on napari.org.

The output is committed; run this again only to pick up a style change:

    pixi run python prototype/make_pygments_css.py <path to napari_code_theme.py>

The path is napari_sphinx_theme/napari_code_theme.py in a napari-sphinx-theme
checkout. It is read from a file so the hub needn't install Sphinx.
"""

import importlib.util
import sys
from pathlib import Path

from pygments.formatters import HtmlFormatter

OUT = Path(__file__).parent / "static" / "pygments.css"


def load_napari_style(path: Path):
    spec = importlib.util.spec_from_file_location("napari_code_theme", path)
    if spec is None or spec.loader is None:
        sys.exit(f"Can't load a Python module from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.NapariCodeTheme


def style_css(style, selector: str) -> str:
    return HtmlFormatter(style=style).get_style_defs(selector)


def main():
    napari_style = load_napari_style(Path(sys.argv[1]))
    light = style_css(napari_style, ".highlight")
    dark = style_css("dracula", ".highlight")
    dark_indented = "\n".join(f"  {line}" for line in dark.splitlines())
    OUT.write_text(
        "/* Generated by prototype/make_pygments_css.py: do not edit.\n"
        "   Light: napari-sphinx-theme's napari style. Dark: dracula. */\n\n"
        f"{light}\n\n"
        "@media (prefers-color-scheme: dark) {\n"
        f"{dark_indented}\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
